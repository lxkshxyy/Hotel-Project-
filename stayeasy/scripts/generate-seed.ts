// Writes supabase/seed.sql from the sample hotels in src/data/hotels.ts.
// Run: npm run seed:sql
import { writeFileSync } from 'node:fs'
import { hotels } from '../src/data/hotels.ts'

const q = (s: string) => `'${s.replace(/'/g, "''")}'`

const rows = hotels
  .map((h) => `  (${q(h.slug)}, ${q(h.city)}, ${q(h.name)}, true, ${q(JSON.stringify(h))}::jsonb)`)
  .join(',\n')

const sql = `-- Sample hotels for StayEasy. Generated by scripts/generate-seed.ts — edit
-- src/data/hotels.ts and re-run \`npm run seed:sql\` rather than editing this file.

insert into public.hotels (slug, city, name, published, data) values
${rows}
on conflict (slug) do update
  set city = excluded.city,
      name = excluded.name,
      published = excluded.published,
      data = excluded.data,
      updated_at = now();
`

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql)
console.log(`Wrote ${hotels.length} hotels to supabase/seed.sql`)
