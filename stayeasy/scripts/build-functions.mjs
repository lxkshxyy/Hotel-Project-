// Bundles the price, availability and Club rules (src/lib/server-core.ts) into one file the
// Supabase functions import, so the server uses exactly the website's maths.
// Run after changing pricing, Club or site settings:  npm run sync:functions
import { build } from 'rolldown'

await build({
  input: 'src/lib/server-core.ts',
  platform: 'neutral',
  output: { file: 'supabase/functions/_shared/core.js', format: 'esm', banner: '// GENERATED by scripts/build-functions.mjs from src/lib/server-core.ts. Do not edit.\n// deno-lint-ignore-file' },
})
console.log('Wrote supabase/functions/_shared/core.js')
